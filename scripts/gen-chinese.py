"""语文完整升级：12 课（order 92-103），每课配 3 道练习"""
import json, os

OUT = os.path.join(os.path.dirname(__file__), '..', 'content', 'lessons')

def E(q, a, b, c, d, answer, explain):
    return {"q": q, "options": [a, b, c, d], "answer": answer, "explain": explain}

def T(id, text, hints, check, opt=False):
    t = {"id": id, "text": text, "hintPrompts": hints, "check": check}
    if opt: t["optional"] = True
    return t

BR = ["island_when_run","island_say","island_say_for","island_move","island_turn_right","island_turn_left","island_goto","island_wait","island_play","island_repeat","island_forever","island_if","island_if_else","island_number","island_random","island_costume","island_change_size","island_eq","island_pen_down","island_pen_up","island_pen_color","island_touching_edge","island_key_down","island_when_key"]

def lesson(id, order, title, emoji, story, goals, actor, targets, tasks, subj_points, intro, celebrate, exercises, band="primary", toolbox=BR, starter=None):
    d = {
        "id": id, "island": "cross", "order": order, "title": title, "emoji": emoji,
        "story": story, "goals": goals, "toolbox": toolbox, "actor": actor,
        "tasks": tasks,
        "curriculum": {"stage": "第二、三学段（1-6年级）" if band == "primary" else "第四学段（7-9年级）", "module": "身边的算法", "points": ["顺序结构", "动画编排"]},
        "subject": {"name": "语文·" + subj_points[0], "emoji": "📖", "points": goals},
        "subjectArea": "语文", "gradeBand": band,
        "aiIntro": intro, "celebrate": celebrate, "exercises": exercises,
        "codeLesson": starter is not None,
    }
    if targets: d["targets"] = targets
    if starter: d["starterCode"] = starter
    json.dump(d, open(os.path.join(OUT, id + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

n = 0
def L(**kw):
    global n
    n += 1
    lesson(**kw)

