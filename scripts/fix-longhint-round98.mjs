const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json'));
let fixed = 0, skipped = 0;
for (const f of files) {
  const p = path.join(DIR, f);
  let data;
  try { data = JSON.parse(fs.readFileSync(p, 'utf8')); } catch { continue; }
  const arr = Array.isArray(data) ? data : [data];
  let changed = false;
  for (const l of arr) {
    for (const [id, qPrefix, expectCorrect, newOpts] of FIX) {
      if (l.id !== id) continue;
      const ex = (l.exercises ?? []).find((e) => (e.q ?? '').startsWith(qPrefix));
      if (!ex) continue;
      if ((ex.options?.[ex.answer] ?? '') !== expectCorrect) {
        skipped++;
        console.log('跳过(正确项不匹配): ' + id + ' ' + qPrefix);
        continue;
      }
      ex.options = newOpts;
      fixed++;
      changed = true;
    }
  }
  if (changed) fs.writeFileSync(p, JSON.stringify(data, null, 2) + '\n', 'utf8');
}
console.log('替换 ' + fixed + ' 题，跳过 ' + skipped + ' 题');
