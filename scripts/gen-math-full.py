def lesson(id, order, title, emoji, story, goals, toolbox, actor, targets, tasks, curr, intro, celeb, band, code=False, starter=None):
    d = {
        "id": id, "island": "math", "order": order, "title": title, "emoji": emoji,
        "story": story, "goals": goals, "toolbox": toolbox, "actor": actor,
        "tasks": tasks,
        "curriculum": curr,
        "subject": {"name": f"数学·{goals[0][:6]}", "emoji": "🔢", "points": goals},
        "subjectArea": "数学", "gradeBand": band,
        "aiIntro": intro, "celebrate": celeb,
    }
    if targets: d["targets"] = targets
    if code:
        d["codeLesson"] = True
        d["starterCode"] = starter
    with open(os.path.join(OUT, id + '.json'), 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)

