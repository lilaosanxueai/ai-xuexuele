def E(q, a, b, c, d, answer, explain):
    return {"q": q, "options": [a, b, c, d], "answer": answer, "explain": explain}

def load(fid):
    import glob
    g = glob.glob(os.path.join(LESSONS, fid + '*.json'))
    p = [x for x in g if os.path.basename(x) == fid + '.json'] or g
    return json.load(open(p[0], encoding='utf-8')), p[0]

def save(p, d):
    json.dump(d, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

