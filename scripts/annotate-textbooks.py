n_tb, n_grade = 0, 0
for f in sorted(L.glob("*.json")):
    d = json.loads(f.read_text(encoding="utf-8"))
    if d.get("id").startswith("hb-"):
        continue  # 河北直通课已在文件里自带标注
    area = d.get("subjectArea") or "信息科技"
    band = d.get("gradeBand") or "primary"
    title = d.get("title", "")
    if d.get("textbook"):
        continue
    grade, textbook = None, VERSION_ONLY.get((area, band))
    for pat, a, g, tb in RULES:
        if area == a and re.search(pat, title):
            grade, textbook = g, tb
            break
    changed = False
    if textbook:
        d["textbook"] = textbook
        n_tb += 1
        changed = True
    if grade is not None:
        d["grade"] = grade
        n_grade += 1
        changed = True
    if changed:
        f.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

