OUT = os.path.join(os.path.dirname(__file__), '..', 'content', 'lessons')

def E(q, a, b, c, d, answer, explain):
    return {"q": q, "options": [a, b, c, d], "answer": answer, "explain": explain}

def T(id, text, hints, check, opt=False):
    t = {"id": id, "text": text, "hintPrompts": hints, "check": check}
    if opt: t["optional"] = True
    return t

def lesson(id, order, title, emoji, area, band, subj_name, story, goals, toolbox, actor, targets, tasks, curr_points, intro, celebrate, exercises, starter=None):
    d = {
        "id": id, "island": "cross", "order": order, "title": title, "emoji": emoji,
        "story": story, "goals": goals, "toolbox": toolbox, "actor": actor,
        "tasks": tasks,
        "curriculum": {"stage": "第四学段（7-9年级）" if band != "primary" else "第二、三学段（3-6年级）", "module": "身边的算法", "points": curr_points},
        "subject": {"name": subj_name, "emoji": "🔬", "points": goals},
        "subjectArea": area, "gradeBand": band,
        "aiIntro": intro, "celebrate": celebrate, "exercises": exercises,
    }
    if targets: d["targets"] = targets
    if starter is not None:
        d["codeLesson"] = True
        d["starterCode"] = starter
    else:
        d["codeLesson"] = False
    json.dump(d, open(os.path.join(OUT, id + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

